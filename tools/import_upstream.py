def imp_javaguide(d, sha):
    groups = {}
    for src in sorted((d / "docs").rglob("*questions*.md")):
        rel = src.relative_to(d / "docs").as_posix()
        rule = next((r for r in JG_RULES if r[0] in rel), None)
        if not rule:
            continue
        _, roles, qtype, topics = rule
        url = f"https://github.com/{SOURCES['javaguide'][0]}/blob/main/docs/{rel}"
        # AI pages list questions as bullets under "常见面试题："; the rest use question headings.
        pattern = r"^- (.+?[？?])\s*$" if rel.startswith("ai/") else r"^#{2,4} (.+?[？?])\s*$"
        in_code = False
        for line in src.read_text(encoding="utf-8").splitlines():
            if line.startswith("```"):
                in_code = not in_code
            m = None if in_code else re.match(pattern, line)
            if not m:
                continue
            raw = m.group(1)
            q = {"q": clean(raw), "url": url}
            if topics:
                q["topics"] = topics
            if "⭐" in raw:
                q["hot"] = True
                q["weight"] = 1.5
            key = (tuple(roles), qtype)
            groups.setdefault(key, []).append(q)
    n = 0
    for (roles, qtype), qs in groups.items():
        name = "-".join(roles) + "-" + qtype
        n += write(f"javaguide/{name}.yml", "javaguide", sha,
                   {"lang": "zh", "type": qtype, "roles": list(roles)}, qs,
                   note="hot: true = marked ⭐️ (high frequency) upstream.")
    return n


