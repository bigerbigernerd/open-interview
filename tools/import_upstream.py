def imp_supergodog(d, sha):
    n = 0
    base = d / "docs" / "01-面试八股文"
    for fname, (qtype, roles, ftopics) in SG_FILES.items():
        qs, section = [], ""
        for line in (base / fname).read_text(encoding="utf-8").splitlines():
            h2 = re.match(r"^## (.+)$", line)
            if h2:
                section = h2.group(1).strip()
                continue
            h3 = re.match(r"^### L\d+ · (.+)$", line)
            if h3:
                q = {"q": clean(h3.group(1))}
                topics = SG_SECTIONS.get(section, ftopics)
                if topics:
                    q["topics"] = topics
                qs.append(q)
                continue
            dep = re.match(r"^\*\*深度\*\*: (\d)/5", line)
            if dep and qs:
                qs[-1]["difficulty"] = int(dep.group(1))
        defaults = {"lang": "zh", "type": qtype, "roles": roles,
                    "url": f"https://github.com/{SOURCES['supergodog'][0]}/blob/main/docs/01-面试八股文/{fname}"}
        n += write(f"supergodog/{fname[:2]}.yml", "supergodog", sha, defaults, qs)
    return n


