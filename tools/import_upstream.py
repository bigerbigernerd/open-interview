def imp_tih(d, sha):
    src = d / "apps" / "website" / "contents" / "behavioral-interview-questions.md"
    qs, company, active = [], None, False
    for line in src.read_text(encoding="utf-8").splitlines():
        h = re.match(r"^## (.+)$", line)
        if h:
            title = h.group(1)
            m = re.match(r"^(.+?) Software Engineer behavioral interview questions", title)
            active = title.startswith("Most commonly asked") or bool(m)
            company = TIH_COMPANY.get(m.group(1)) if m else None
            continue
        m = re.match(r"^\s*(?:\d+\.|[-*]) (.+)$", line)
        if active and m:
            text = clean(m.group(1))
            if len(text) < 12 or text.endswith(":"):
                continue
            q = {"q": text}
            if company:
                q["companies"] = [company]
            qs.append(q)
    return write("tech-interview-handbook/behavioral.yml", "tih", sha,
                 {"lang": "en", "type": "behavioral",
                  "url": f"https://github.com/{SOURCES['tih'][0]}/blob/main/apps/website/contents/behavioral-interview-questions.md"},
                 qs)


KDN_COMPANY = {"facebook": "meta", "snapchat": "snap"}


def imp_kdn251(d, sha):
    qs = []
    for path in sh("git", "ls-tree", "-r", "--name-only", "HEAD", cwd=d).splitlines():
        m = re.match(r"^company/([a-z]+)/([A-Za-z0-9]+)\.java$", path)
        if not m:
            continue
        company = KDN_COMPANY.get(m.group(1), m.group(1))
        title = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", " ", m.group(2))
        title = re.sub(r"(?<=[A-Za-z])(?=\d)", " ", title)
        qs.append({"q": f"Coding: {title}", "companies": [company],
                   "url": f"https://github.com/{SOURCES['kdn251'][0]}/blob/master/{path}"})
    return write("kdn251/company-coding.yml", "kdn251", sha,
                 {"lang": "en", "type": "coding", "roles": ["swe"], "topics": ["algorithms"]},
                 sorted(qs, key=lambda q: q["q"]),
                 note="Titles name classic LeetCode-style problems; the agent states the full problem.")


def imp_sdp(d, sha):
    text = (d / "README.md").read_text(encoding="utf-8")
    sections = {
        "System design interview questions with solutions": ["distributed-systems"],
        "Object-oriented design interview questions with solutions": ["ood"],
        "Additional system design interview questions": ["distributed-systems"],
    }
    qs = []
    for title, topics in sections.items():
        block = re.split(rf"^#{{2,3}} {re.escape(title)}\s*$", text, maxsplit=1, flags=re.M)[1]
        block = re.split(r"^#{2,3} ", block, maxsplit=1, flags=re.M)[0]
        for line in block.splitlines():
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if not line.startswith("|") or len(cells) < 2 or cells[0] in ("Question", "") or set(cells[0]) <= set("-:"):
                continue
            q = clean(cells[0])
            if q.lower().startswith("add a") or "contribute" in cells[-1].lower():
                continue
            qs.append({"q": q, "topics": topics})
    return write("system-design-primer/system-design.yml", "sdp", sha,
                 {"lang": "en", "type": "system-design", "roles": ["swe"], "difficulty": 3,
                  "url": f"https://github.com/{SOURCES['sdp'][0]}#system-design-interview-questions-with-solutions"},
                 qs)


