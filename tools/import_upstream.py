# ---------- helpers ----------

def sh(*args, cwd=None):
    return subprocess.run(args, cwd=cwd, check=True, capture_output=True, text=True).stdout.strip()


def checkout(key, offline):
    repo, _ = SOURCES[key]
    d = CACHE / repo.replace("/", "__")
    if not d.exists():
        if offline:
            sys.exit(f"missing clone {d}; run without --offline")
        CACHE.mkdir(parents=True, exist_ok=True)
        sh("git", "clone", "-q", "--depth", "1", "--filter=blob:none", "--sparse",
           f"https://github.com/{repo}", str(d))
        sh("git", "sparse-checkout", "set", "--no-cone", *SPARSE, cwd=d)
    elif not offline:
        sh("git", "pull", "-q", "--depth", "1", cwd=d)
    return d, sh("git", "rev-parse", "--short", "HEAD", cwd=d)


MD_LINK = re.compile(r"\[([^\]]+)\]\([^)]*\)")


def clean(text):
    text = MD_LINK.sub(r"\1", html.unescape(text))
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text)
    text = text.replace("⭐️", "").replace("⭐", "")
    return re.sub(r"\s+", " ", text).strip()


def norm(text):
    return re.sub(r"[\W_]+", "", text.lower())


class Flow(list):
    """Lists of scalars render inline: roles: [frontend]."""


yaml.SafeDumper.add_representer(
    Flow, lambda d, v: d.represent_sequence("tag:yaml.org,2002:seq", v, flow_style=True))


def flowify(obj):
    if isinstance(obj, dict):
        return {k: flowify(v) for k, v in obj.items()}
    if isinstance(obj, list):
        if all(isinstance(x, (str, int, float)) for x in obj) and sum(len(str(x)) for x in obj) < 80:
            return Flow(obj)
        return [flowify(x) for x in obj]
    return obj


def write(rel, key, sha, defaults, questions, note=""):
    repo, lic = SOURCES[key]
    seen, uniq = {}, []
    for q in questions:  # merge duplicates inside one file, unioning companies
        k = norm(q["q"])
        if not k:
            continue
        if k in seen:
            prev = seen[k]
            for field in ("companies", "topics"):
                if q.get(field):
                    prev[field] = sorted(set(prev.get(field, [])) | set(q[field]))
            continue
        seen[k] = q
        uniq.append(q)
    doc = {
        "source": {"name": repo, "url": f"https://github.com/{repo}", "license": lic, "commit": sha},
        "defaults": defaults,
        "questions": uniq,
    }
    path = OUT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    header = (f"# GENERATED by tools/import_upstream.py from {repo}@{sha} ({lic}).\n"
              f"# Do not edit by hand. {note}\n")
    body = yaml.safe_dump(flowify(doc), allow_unicode=True, sort_keys=False, width=1000)
    path.write_text(header + body, encoding="utf-8")
    print(f"  {rel}: {len(uniq)} questions")
    return len(uniq)


# ---------- importers ----------

def imp_h5bp(d, sha):
    files = {
        "html": ("technical", ["html"]),
        "css": ("technical", ["css"]),
        "javascript": ("technical", ["javascript"]),
        "network": ("technical", ["network", "browser"]),
        "performance": ("technical", ["web-performance"]),
        "testing": ("technical", ["testing"]),
        "general": ("behavioral", []),
        "fun": ("behavioral", []),
    }
    n = 0
    for name, (qtype, topics) in files.items():
        src = d / "src" / "questions" / f"{name}-questions.md"
        qs, cur = [], None
        for line in src.read_text(encoding="utf-8").splitlines():
            m = re.match(r"^(\s*)[*-] (.+)$", line)
            if not m:
                continue
            text = clean(m.group(2))
            if not m.group(1):
                cur = {"q": text}
                if topics:
                    cur["topics"] = topics
                qs.append(cur)
            elif cur is not None:
                cur.setdefault("followups", []).append(text)
        url = f"https://github.com/{SOURCES['h5bp'][0]}/blob/main/src/questions/{name}-questions.md"
        n += write(f"h5bp/{name}.yml", "h5bp", sha,
                   {"lang": "en", "type": qtype, "roles": ["frontend"], "url": url}, qs)
    return n


NEEDS_CONTEXT = re.compile(r"下面|以下|如下|下列|输出|结果是|这段|该代码|图中|上图|写出结果")


def imp_haizlin(d, sha):
    files = {"html": ["html"], "css": ["css"], "js": ["javascript"], "nodejs": ["nodejs"],
             "ECMAScript": ["javascript"], "skill": ["engineering"]}
    n = 0
    for name, topics in files.items():
        qs = []
        for line in (d / "category" / f"{name}.md").read_text(encoding="utf-8").splitlines():
            m = re.match(r"^- \[(.+)\]\((https://github\.com/haizlin/fe-interview/issues/\d+)\)", line)
            if not m or NEEDS_CONTEXT.search(m.group(1)):
                continue
            qs.append({"q": clean(m.group(1)), "url": m.group(2)})
        n += write(f"haizlin/{name.lower()}.yml", "haizlin", sha,
                   {"lang": "zh", "type": "technical", "roles": ["frontend"], "topics": topics,
                    "weight": 0.4},
                   qs, note="Questions that depend on a code snippet only shown upstream are skipped.")
    return n


