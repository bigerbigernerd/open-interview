def imp_javaguide(d, sha):
    groups = {}
    for src in sorted((d / "docs").rglob("*questions*.md")):
        rel = src.relative_to(d / "docs").as_posix()
        rule = next((r for r in JG_RULES if r[0] in rel), None)
        if not rule:
            continue
        _, roles, qtype, topics = rule
        url = f"https://github.com/{SOURCES['javaguide'][0]}/blob/main/docs/{rel}"
        # AI pages list questions as bullets under "常见面试题："; the rest use question headings.
        pattern = r"^- (.+?[？?])\s*$" if rel.startswith("ai/") else r"^#{2,4} (.+?[？?])\s*$"
        in_code = False
        for line in src.read_text(encoding="utf-8").splitlines():
            if line.startswith("```"):
                in_code = not in_code
            m = None if in_code else re.match(pattern, line)
            if not m:
                continue
            raw = m.group(1)
            q = {"q": clean(raw), "url": url}
            if topics:
                q["topics"] = topics
            if "⭐" in raw:
                q["hot"] = True
                q["weight"] = 1.5
            key = (tuple(roles), qtype)
            groups.setdefault(key, []).append(q)
    n = 0
    for (roles, qtype), qs in groups.items():
        name = "-".join(roles) + "-" + qtype
        n += write(f"javaguide/{name}.yml", "javaguide", sha,
                   {"lang": "zh", "type": qtype, "roles": list(roles)}, qs,
                   note="hot: true = marked ⭐️ (high frequency) upstream.")
    return n


IMPORTERS = {"h5bp": imp_h5bp, "haizlin": imp_haizlin, "tih": imp_tih, "kdn251": imp_kdn251,
             "sdp": imp_sdp, "supergodog": imp_supergodog, "misterbooo": imp_misterbooo,
             "javaguide": imp_javaguide}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--offline", action="store_true", help="reuse clones in .cache/upstream")
    ap.add_argument("only", nargs="*", help=f"subset of: {' '.join(IMPORTERS)}")
    args = ap.parse_args()
    total = 0
    for key in args.only or IMPORTERS:
        d, sha = checkout(key, args.offline)
        print(f"{SOURCES[key][0]}@{sha}")
        total += IMPORTERS[key](d, sha)
        lic = next(iter(sorted(d.glob("LICENSE*"))), None)
        if lic:  # keep the upstream license text next to the imported files
            (OUT / OUT_DIR[key] / "UPSTREAM-LICENSE.txt").write_text(
                f"License of https://github.com/{SOURCES[key][0]} (commit {sha}):\n\n" + lic.read_text(encoding="utf-8"),
                encoding="utf-8")
    print(f"total {total}")


if __name__ == "__main__":
    main()
